-- one replication set per worker; the filter and the columns live on the set membership
SELECT pglogical.create_replication_set('ref_w' || n) FROM generate_series(1, 2) n;
SELECT pglogical.replication_set_add_table('ref_w' || n, 'plans') FROM generate_series(1, 2) n;
SELECT pglogical.replication_set_add_table('ref_w' || n, 'prices') FROM generate_series(1, 2) n;
SELECT pglogical.replication_set_add_table(
         set_name := 'ref_w' || n, relation := 'customers', synchronize_data := false,
         columns := ARRAY['customer_id', 'name', 'worker_id', 'plan_id'],
         row_filter := 'worker_id = ' || n)
FROM generate_series(1, 2) n;
SELECT s.set_name, t.set_reloid::regclass AS tbl, t.set_att_list, t.set_row_filter
FROM pglogical.replication_set_table t JOIN pglogical.replication_set s USING (set_id)
WHERE t.set_reloid = 'customers'::regclass ORDER BY 1;
