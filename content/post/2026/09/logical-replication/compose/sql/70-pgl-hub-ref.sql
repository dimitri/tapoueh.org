-- @service: pghub
-- Step 7a (pglogical 2.4.8 on PostgreSQL 14). Hub: node, reference tables, one replication set
-- per worker holding the tables with a row_filter and a column list.
CREATE EXTENSION pglogical;
SELECT pglogical.create_node(node_name := 'hub', dsn := 'host=pghub dbname=app user=postgres');

CREATE TABLE plans (plan_id int PRIMARY KEY, name text NOT NULL);
CREATE TABLE prices (plan_id int REFERENCES plans, meter text, unit_price numeric(10,4) NOT NULL, PRIMARY KEY (plan_id, meter));
CREATE TABLE customers (
  customer_id   int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          text NOT NULL,
  worker_id     int NOT NULL,
  plan_id       int NOT NULL REFERENCES plans,
  billing_notes text
);
