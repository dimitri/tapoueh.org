INSERT INTO orders (customer_id, amount, client_seq)
  SELECT 1 + (g % 50000), (g % 500) + 0.99, -g FROM generate_series(1, 600000) g;
INSERT INTO audit_log (event, payload)
  SELECT 'seed', 'row ' || g FROM generate_series(1, 100000) g;
INSERT INTO counters VALUES ('orders', 0);
INSERT INTO measurements (ts, sensor, value)
  SELECT now() - (g || ' seconds')::interval, g % 10, random()
    FROM generate_series(1, 300000) g;
INSERT INTO documents VALUES
  (1, 'manual', lo_from_bytea(0, convert_to(repeat('lorem ipsum ', 5000), 'UTF8')));

-- (7) a materialized view
CREATE MATERIALIZED VIEW sales_by_day AS
  SELECT date_trunc('day', created_at) AS day, count(*) AS orders, sum(amount) AS total
    FROM orders GROUP BY 1;
CREATE UNIQUE INDEX ON sales_by_day (day);

RESET ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA public TO reporting;
ANALYZE;

