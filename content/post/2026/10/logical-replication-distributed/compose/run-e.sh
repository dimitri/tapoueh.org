#!/usr/bin/env bash
# Profile e: Part 1's three pglogical findings, re-run on PostgreSQL 18, then
# two writers hammering the same keys under each conflict-resolution policy.
#
#   ./reset-e.sh && ./run-e.sh findings
#   ./run-e.sh concurrent
#   ./run-e.sh ddl        schema changes between two writers: plain ALTER TABLE, then
#                         pglogical.replicate_ddl_command, then a RENAME under load
#   ./run-e.sh failover   a provider with a physical standby (e-w1, e-s1) feeding a subscriber
#                         (e-w2); the provider is killed and the standby promoted.
#                         FAILOVER_SLOT=0 leaves the slot as pglogical created it
#   ./reset-e.sh && ./run-e.sh bench native|pglogical|pgcopydb
#                         latency and rows a second of the same one-way link e-w1 -> e-w2
set -uo pipefail
cd "$(dirname "$0")"
mkdir -p results

dc() { docker compose -p lrdist "$@"; }
q()  { local n=$1; shift; dc exec -T "$n" psql -X -q -U postgres -d app -v ON_ERROR_STOP=0 "$@" 2>&1; }
qa() { local n=$1; shift; dc exec -T "$n" psql -X -At -U postgres -d app "$@" 2>&1; }
# wait for a boolean SQL expression on a node, up to $3 seconds
wait_for() { local n=$1 cond=$2 t=${3:-30} i; for i in $(seq 1 "$t"); do
  [ "$(qa "$n" -c "select ($cond)" | tail -1)" = t ] && return 0; sleep 1; done; return 1; }

findings() {
  local out=results/e-findings.out
  {
  echo "== versions =="
  qa e-hub -c "select version()"
  qa e-hub -c "create extension if not exists pglogical; select 'pglogical ' || extversion from pg_extension where extname = 'pglogical'"

  echo; echo "== nodes and reference data (hub), one replication set per worker, row filter + column list =="
  q e-hub <<'SQL'
select pglogical.create_node(node_name := 'hub', dsn := 'host=e-hub dbname=app user=postgres');
create table plans (plan_id int primary key, name text not null);
create table customers (customer_id int generated by default as identity primary key,
  name text not null, worker_id int not null, plan_id int not null references plans, billing_notes text);
insert into plans values (1,'basic'),(2,'pro'),(3,'enterprise');
insert into customers (name, worker_id, plan_id, billing_notes)
  select 'customer-' || n, (n - 1) / 3 + 1, (n - 1) % 3 + 1, 'secret ' || n from generate_series(1, 6) n;
select pglogical.create_replication_set('ref_w' || n) from generate_series(1, 2) n;
select pglogical.replication_set_add_table('ref_w' || n, 'plans') from generate_series(1, 2) n;
select pglogical.replication_set_add_table(set_name := 'ref_w' || n, relation := 'customers',
  synchronize_data := false, columns := array['customer_id','name','worker_id','plan_id'],
  row_filter := 'worker_id = ' || n) from generate_series(1, 2) n;
SQL
  for n in 1 2; do
    q e-w$n -v n=$n <<'SQL'
create extension pglogical;
select pglogical.create_node(node_name := 'worker' || :n, dsn := 'host=e-w' || :n || ' dbname=app user=postgres');
create table plans (plan_id int primary key, name text not null);
create table customers (customer_id int primary key, name text not null, worker_id int not null, plan_id int not null);
select pglogical.create_subscription(subscription_name := 'sub_ref_w' || :n,
  provider_dsn := 'host=e-hub dbname=app user=postgres', replication_sets := array['ref_w' || :n],
  synchronize_data := true, forward_origins := '{}') is not null as created;
select pglogical.wait_for_subscription_sync_complete('sub_ref_w' || :n);
SQL
  done
  q e-hub -c "create extension if not exists pglogical" >/dev/null

  echo; echo "== finding 2: move customer 3 from worker 1's filter to worker 2's =="
  q e-hub -c "update customers set worker_id = 2 where customer_id = 3"
  q e-hub -c "insert into customers (name, worker_id, plan_id) values ('marker-w1', 1, 1), ('marker-w2', 2, 1)"
  wait_for e-w1 "exists (select 1 from customers where name = 'marker-w1')"
  wait_for e-w2 "exists (select 1 from customers where name = 'marker-w2')"
  for n in 1 2; do echo "-- worker$n"; q e-w$n -c "select customer_id, name, worker_id from customers order by 1"; done
  echo "-- hub"; q e-hub -c "select customer_id, name, worker_id from customers order by 1"

  echo; echo "== finding 1: replicate into a partitioned parent =="
  q e-w1 <<'SQL'
create table ue_crash (worker_id int not null default 1, event_id bigint not null, qty int not null, primary key (worker_id, event_id));
insert into ue_crash (event_id, qty) values (1, 1);
select pglogical.create_replication_set('crash');
select pglogical.replication_set_add_table('crash', 'ue_crash');
SQL
  q e-hub <<'SQL'
create table ue_crash (worker_id int not null, event_id bigint not null, qty int not null, primary key (worker_id, event_id))
  partition by list (worker_id);
create table ue_crash_w1 partition of ue_crash for values in (1);
select pglogical.create_subscription(subscription_name := 'sub_crash',
  provider_dsn := 'host=e-w1 dbname=app user=postgres', replication_sets := array['crash'],
  synchronize_data := true, forward_origins := '{}') is not null as created;
select pglogical.wait_for_subscription_sync_complete('sub_crash');
select count(*) as rows_copied_by_initial_sync from ue_crash;
SQL
  local since; since=$(date -u +%Y-%m-%dT%H:%M:%SZ)
  q e-w1 -c "insert into ue_crash (event_id, qty) values (2, 2)"
  if wait_for e-hub "(select count(*) from ue_crash) = 2" 20; then
    echo "second row replicated into the partitioned parent: NO crash"
  else
    echo "second row never arrived within 20s"
  fi
  echo "-- hub server log since the INSERT (signal / crash lines)"
  dc logs --since "$since" e-hub 2>&1 | grep -i "signal\|terminated\|segmentation\|crash\|pglogical apply" | sed 's/^[^|]*| //' | head -8
  echo "-- apply-worker crashes logged since the INSERT (about 30 s)"
  sleep 10
  dc logs --since "$since" e-hub 2>&1 | grep -c "terminated by signal 11"
  echo "-- dropping the subscription (retried: the server is restarting in a loop)"
  for i in $(seq 1 60); do
    q e-hub -c "select pglogical.drop_subscription('sub_crash')" 2>&1 | grep -q "drop_subscription" && { echo "dropped after $i attempt(s)"; break; }
    sleep 0.5
  done
  } 2>&1 | tee "$out"
}

# --- concurrent writers --------------------------------------------------------
# Two nodes (e-w1, e-w2), subscribed to each other, both rewriting the same keys at
# the same time. One run per conflict-resolution policy, each on a fresh table.
setup_conc() { # policy
  local pol=$1 t="conc_$1"
  for n in 1 2; do
    q e-w$n <<SQL >/dev/null
create table $t (id int primary key, v int not null, writer text not null);
insert into $t select g, 0, 'seed' from generate_series(1, 1000) g;
select pglogical.create_replication_set('set_$pol');
select pglogical.replication_set_add_table('set_$pol', '$t');
SQL
  done
  q e-w1 -c "select pglogical.create_subscription(subscription_name := 'sub_${pol}_w1_from_w2', provider_dsn := 'host=e-w2 dbname=app user=postgres', replication_sets := array['set_$pol'], synchronize_data := false, forward_origins := '{}')" >/dev/null
  q e-w2 -c "select pglogical.create_subscription(subscription_name := 'sub_${pol}_w2_from_w1', provider_dsn := 'host=e-w1 dbname=app user=postgres', replication_sets := array['set_$pol'], synchronize_data := false, forward_origins := '{}')" >/dev/null
  wait_for e-w1 "(select count(*) from pglogical.show_subscription_status() where subscription_name like 'sub_${pol}_%' and status = 'replicating') = 1" 30
  wait_for e-w2 "(select count(*) from pglogical.show_subscription_status() where subscription_name like 'sub_${pol}_%' and status = 'replicating') = 1" 30
}

writer() { # node tag table seconds
  dc exec -T "$1" sh -c "cat > /tmp/w.sql <<'EOS'
\\set id random(1, 1000)
update $3 set v = v + 1, writer = '$2' where id = :id;
EOS
pgbench -n -U postgres -d app -c 4 -j 2 -R 2000 -T $4 -f /tmp/w.sql 2>&1 | grep -E 'transactions actually|number of failed|tps'" 
}

snapshot() { qa "$1" -c "select id, v, writer from $2 order by id" | md5sum | cut -c1-12; }
diff_rows() { # table: rows that differ between the two nodes
  local a b; a=$(mktemp); b=$(mktemp)
  qa e-w1 -c "select id, v, writer from $1 order by id" > "$a"
  qa e-w2 -c "select id, v, writer from $1 order by id" > "$b"
  diff "$a" "$b" | grep -c '^<'; rm -f "$a" "$b"
}

run_policy() { # policy seconds
  local pol=$1 secs=${2:-15} t="conc_$1" since
  case "$pol" in
    error|apply_remote|keep_local|last_update_wins|first_update_wins) ;;
    *) echo "unknown policy $pol"; return 1 ;;
  esac
  for n in e-w1 e-w2; do q $n -c "alter system set pglogical.conflict_resolution = '$pol'" >/dev/null; q $n -c "select pg_reload_conf()" >/dev/null; done
  sleep 1
  setup_conc "$pol"
  since=$(date -u +%Y-%m-%dT%H:%M:%SZ)
  echo "== policy: $pol ($secs s, 4 clients per node, same 1000 keys) =="
  writer e-w1 w1 "$t" "$secs" > /tmp/e-w1.$$ &
  writer e-w2 w2 "$t" "$secs" > /tmp/e-w2.$$ &
  wait
  local c1 c2
  c1=$(grep 'transactions actually' /tmp/e-w1.$$ | head -1 | grep -o '[0-9]*$')
  c2=$(grep 'transactions actually' /tmp/e-w2.$$ | head -1 | grep -o '[0-9]*$')
  rm -f /tmp/e-w1.$$ /tmp/e-w2.$$
  echo "committed UPDATEs: w1=$c1 w2=$c2 (total $((c1 + c2)))"
  # let replication drain: stop when both snapshots are identical and stable, or after 60s
  local s1 s2 stable=0 i
  for i in $(seq 1 60); do
    s1=$(snapshot e-w1 "$t"); s2=$(snapshot e-w2 "$t")
    if [ "$s1" = "$s2" ]; then stable=$((stable+1)); [ $stable -ge 3 ] && break; else stable=0; fi
    sleep 1
  done
  echo "snapshots after settling: w1=$s1 w2=$s2 -> $([ "$s1" = "$s2" ] && echo CONVERGED || echo DIVERGED)"
  echo "rows that differ between the nodes: $(diff_rows "$t") of 1000"
  local sv1 sv2
  sv1=$(qa e-w1 -c "select sum(v) from $t"); sv2=$(qa e-w2 -c "select sum(v) from $t")
  echo "sum(v) (every UPDATE adds 1): w1=$sv1 w2=$sv2 -> UPDATEs not reflected in w1's total: $((c1 + c2 - sv1)) (meaningful when converged)"
  for n in e-w1 e-w2; do
    echo "$n conflict log lines by resolution:"
    dc logs --since "$since" $n 2>&1 | grep -o 'CONFLICT: .*Resolution: [a-z_]*' | sed 's/.*Resolution: //' | sort | uniq -c | sed 's/^/   /'
  done
  echo "subscription status:"
  q e-w1 -c "select subscription_name, status from pglogical.show_subscription_status() where subscription_name like 'sub_${pol}_%'" | sed 's/^/   /'
  q e-w2 -c "select subscription_name, status from pglogical.show_subscription_status() where subscription_name like 'sub_${pol}_%'" | sed 's/^/   /'
  echo
}

ensure_nodes() {
  for n in 1 2; do
    q e-w$n <<SQL >/dev/null
create extension if not exists pglogical;
select pglogical.create_node(node_name := 'worker$n', dsn := 'host=e-w$n dbname=app user=postgres')
  where not exists (select 1 from pglogical.node);
SQL
  done
}

concurrent() {
  local out=results/e-concurrent.out secs=${SECS:-15}
  ensure_nodes
  { for pol in last_update_wins apply_remote keep_local first_update_wins error; do
      run_policy "$pol" "$secs"
    done; } 2>&1 | tee "$out"
}

# --- DDL ---------------------------------------------------------------------------
# e-w1 and e-w2 subscribe to each other (the table's replication set and ddl_sql) and both
# keep inserting. Three schema changes, each timed from the moment it is issued.
ddl() {
  local out=results/e-ddl.out
  ensure_nodes
  {
  echo "== slots pglogical creates on the provider (failover column) =="
  for n in 1 2; do
    q e-w$n <<SQL >/dev/null
create table ddl_t (id bigint primary key, src text not null, v int not null default 0);
select pglogical.create_replication_set('set_ddl');
select pglogical.replication_set_add_table('set_ddl', 'ddl_t');
SQL
  done
  q e-w1 -c "select pglogical.create_subscription(subscription_name := 'sub_ddl_w1_from_w2', provider_dsn := 'host=e-w2 dbname=app user=postgres', replication_sets := array['set_ddl','ddl_sql'], synchronize_data := false, forward_origins := '{}')" >/dev/null
  q e-w2 -c "select pglogical.create_subscription(subscription_name := 'sub_ddl_w2_from_w1', provider_dsn := 'host=e-w1 dbname=app user=postgres', replication_sets := array['set_ddl','ddl_sql'], synchronize_data := false, forward_origins := '{}')" >/dev/null
  wait_for e-w1 "(select count(*) from pglogical.show_subscription_status() where subscription_name = 'sub_ddl_w1_from_w2' and status = 'replicating') = 1" 30
  wait_for e-w2 "(select count(*) from pglogical.show_subscription_status() where subscription_name = 'sub_ddl_w2_from_w1' and status = 'replicating') = 1" 30
  qa e-w1 -c "select slot_name || ' failover=' || failover from pg_replication_slots where plugin = 'pglogical_output'"

  # two inserters, one per node, ids from disjoint ranges
  dc exec -T e-w1 rm -f /tmp/ddl-stop; dc exec -T e-w2 rm -f /tmp/ddl-stop
  for n in 1 2; do
    dc exec -d e-w$n sh -c "i=$((n * 100000000)); while [ ! -e /tmp/ddl-stop ]; do psql -X -q -U postgres -d app -c \"insert into ddl_t (id, src) values (\$i, 'w$n')\" 2>/dev/null; i=\$((i + 1)); sleep 0.02; done"
  done
  sleep 8
  lag() { # rows of the node $1 not yet on the node $2
    echo $(( $(qa "$1" -c "select count(*) from ddl_t where src = '${1#e-}'") - $(qa "$2" -c "select count(*) from ddl_t where src = '${1#e-}'") ))
  }
  status() { q e-w1 -At -c "select status from pglogical.show_subscription_status() where subscription_name = 'sub_ddl_w1_from_w2'"; }
  status2() { q e-w2 -At -c "select status from pglogical.show_subscription_status() where subscription_name = 'sub_ddl_w2_from_w1'"; }
  echo "steady state: lag w1->w2 $(lag e-w1 e-w2), w2->w1 $(lag e-w2 e-w1); $(status) / $(status2)"

  echo; echo "== 1: plain ALTER TABLE ... ADD COLUMN on w1 only =="
  t1=$(date +%s)
  q e-w1 -c "alter table ddl_t add column plain_col text" >/dev/null
  sleep 10
  echo "10 s later: lag w1->w2 $(lag e-w1 e-w2) rows; w2 sees the column: $(qa e-w2 -c "select count(*) from information_schema.columns where table_name = 'ddl_t' and column_name = 'plain_col'"); subscription on w2: $(status2)"
  echo "w2 log: $(dc logs --tail 300 e-w2 2>&1 | grep -m1 'unknown column name' | sed 's/^[^|]*| //')"
  t2=$(date +%s)
  q e-w2 -c "alter table ddl_t add column plain_col text" >/dev/null
  for i in $(seq 1 180); do
    [ "$(status2)" = replicating ] && [ "$(lag e-w1 e-w2)" -le 3 ] && break; sleep 2
  done
  echo "the same ALTER by hand on w2 at +$((t2 - t1)) s; the subscription is replicating and caught up at +$(( $(date +%s) - t1 )) s ($(status2), lag $(lag e-w1 e-w2) rows)"

  for i in $(seq 1 120); do [ "$(status)" = replicating ] && [ "$(status2)" = replicating ] && [ "$(lag e-w1 e-w2)" -le 3 ] && [ "$(lag e-w2 e-w1)" -le 3 ] && break; sleep 1; done
  echo; echo "== 2: pglogical.replicate_ddl_command('... ADD COLUMN') on w1, both writers running =="
  q e-w1 -c "select pglogical.replicate_ddl_command('alter table public.ddl_t add column queued_col text')" >/dev/null
  mx=0; for i in $(seq 1 10); do l1=$(lag e-w1 e-w2); l2=$(lag e-w2 e-w1); m=$(( l1 > l2 ? l1 : l2 )); [ $m -gt $mx ] && mx=$m; sleep 1; done
  echo "w2 has the column, nothing run there: $(qa e-w2 -c "select count(*) from information_schema.columns where table_name = 'ddl_t' and column_name = 'queued_col'"); largest lag over 10 s: $mx rows; subscriptions: $(status) / $(status2)"

  echo; echo "== 3: pglogical.replicate_ddl_command('... RENAME COLUMN') on w1, both writers running =="
  q e-w1 -c "select pglogical.replicate_ddl_command('alter table public.ddl_t rename column queued_col to renamed_col')" >/dev/null
  mx=0; for i in $(seq 1 15); do l1=$(lag e-w1 e-w2); l2=$(lag e-w2 e-w1); m=$(( l1 > l2 ? l1 : l2 )); [ $m -gt $mx ] && mx=$m; sleep 1; done
  echo "(15 s after the RENAME)"
  echo "column renamed on w2: $(qa e-w2 -c "select count(*) from information_schema.columns where table_name = 'ddl_t' and column_name = 'renamed_col'"); lag w1->w2 $(lag e-w1 e-w2), w2->w1 $(lag e-w2 e-w1); subscriptions: $(status) / $(status2)"
  echo "log lines about the rename: $(dc logs --tail 400 e-w1 e-w2 2>&1 | grep -c -i 'queued_col\|renamed_col')"
  dc exec -T e-w1 touch /tmp/ddl-stop; dc exec -T e-w2 touch /tmp/ddl-stop
  } 2>&1 | tee "$out"
}

# pglogical creates its slot with the 2ndQuadrant syntax (CREATE_REPLICATION_SLOT ... FAILOVER),
# which community Postgres does not parse, so the slot is a plain one. Postgres 17's replication
# command ALTER_REPLICATION_SLOT turns the flag on afterwards, while the slot is inactive.
failover() {
  local out=results/e-failover-${FAILOVER_SLOT:-1}.out
  local PGDATA=/var/lib/postgresql/18/docker SLOT i
  local PGL="-c shared_preload_libraries=pglogical -c output_plugin_libraries=pglogical_output -c wal_level=logical -c track_commit_timestamp=on -c max_worker_processes=24 -c max_replication_slots=16 -c max_wal_senders=16 -c max_logical_replication_workers=12 -c wal_retrieve_retry_interval=1s"
  dc up -d --wait e-w1 e-w2 >/dev/null 2>&1
  dc up -d e-s1 >/dev/null 2>&1
  {
  echo "== provider e-w1, physical standby e-s1, subscriber e-w2 (FAILOVER_SLOT=${FAILOVER_SLOT:-1}) =="
  q e-w1 <<'SQL' >/dev/null
create extension pglogical;
select pglogical.create_node(node_name := 'provider', dsn := 'host=e-w1 dbname=app user=postgres');
create table events (id bigint primary key, note text);
select pglogical.replication_set_add_table('default', 'events');
select pg_create_physical_replication_slot('e_s1_slot');
alter system set synchronized_standby_slots = 'e_s1_slot';
SQL
  dc exec -T e-w1 sh -c "echo 'host replication all all trust' >> $PGDATA/pg_hba.conf"
  q e-w1 -c "select pg_reload_conf()" >/dev/null
  dc exec -T -u postgres e-s1 sh -c "pg_basebackup -h e-w1 -U postgres -D $PGDATA -X stream -S e_s1_slot --write-recovery-conf >/dev/null 2>&1 \
    && printf \"primary_conninfo = 'host=e-w1 user=postgres dbname=app'\nsync_replication_slots = on\nhot_standby_feedback = on\n\" >> $PGDATA/postgresql.auto.conf \
    && pg_ctl -D $PGDATA -o '$PGL' -l /tmp/standby.log -w start >/dev/null"
  wait_for e-s1 "pg_is_in_recovery()" 30
  echo "standby: in recovery $(qa e-s1 -c 'select pg_is_in_recovery()'), sync_replication_slots=$(qa e-s1 -c 'show sync_replication_slots')"

  q e-w2 <<'SQL' >/dev/null
create extension pglogical;
select pglogical.create_node(node_name := 'subscriber', dsn := 'host=e-w2 dbname=app user=postgres');
create table events (id bigint primary key, note text);
SQL
  q e-w2 -c "select pglogical.create_subscription(subscription_name := 'sub', provider_dsn := 'host=e-w1,e-s1 dbname=app user=postgres target_session_attrs=read-write', synchronize_data := false)" >/dev/null
  wait_for e-w2 "(select count(*) from pglogical.show_subscription_status() where status = 'replicating') = 1" 60
  SLOT=$(qa e-w1 -c "select slot_name from pg_replication_slots where plugin = 'pglogical_output'")
  echo "slot pglogical created on the provider: $(qa e-w1 -c "select slot_name || ' failover=' || failover from pg_replication_slots where plugin = 'pglogical_output'")"

  if [ "${FAILOVER_SLOT:-1}" = 1 ]; then
    echo; echo "== ALTER_REPLICATION_SLOT \"$SLOT\" ( FAILOVER true ), subscription disabled meanwhile =="
    q e-w2 -c "select pglogical.alter_subscription_disable('sub', true)" >/dev/null
    wait_for e-w1 "not (select active from pg_replication_slots where slot_name = '$SLOT')" 30
    dc exec -T e-w1 psql -X -U postgres "dbname=app replication=database" -c "ALTER_REPLICATION_SLOT \"$SLOT\" ( FAILOVER true )" 2>&1
    q e-w2 -c "select pglogical.alter_subscription_enable('sub', true)" >/dev/null
    wait_for e-w2 "(select count(*) from pglogical.show_subscription_status() where status = 'replicating') = 1" 60
  fi
  echo "slot on the provider now: $(qa e-w1 -c "select slot_name || ' failover=' || failover from pg_replication_slots where plugin = 'pglogical_output'")"
  for i in $(seq 1 60); do
    [ "$(qa e-s1 -c "select count(*) from pg_replication_slots where slot_name = '$SLOT' and synced and not temporary")" = 1 ] && break; sleep 1
  done
  echo "on the standby: $(qa e-s1 -c "select coalesce(string_agg(slot_name || ' failover=' || failover || ' synced=' || synced, ', '), 'no logical slot') from pg_replication_slots where slot_type = 'logical'")"

  # a writer on the provider, one numbered row at a time; the ids it was acknowledged for are kept outside the database
  dc exec -T e-w1 rm -f /tmp/fo-stop /tmp/fo-acked
  dc exec -d e-w1 sh -c "i=1; while [ ! -e /tmp/fo-stop ]; do psql -X -q -U postgres -d app -c \"insert into events values (\$i, 'p')\" 2>/dev/null && echo \$i >> /tmp/fo-acked; i=\$((i + 1)); sleep 0.02; done"
  sleep 10
  echo; echo "steady state: provider $(qa e-w1 -c 'select count(*) from events') rows, subscriber $(qa e-w2 -c 'select count(*) from events')"
  echo "== docker kill e-w1; pg_ctl promote on e-s1 =="
  T0=$(date +%s)
  dc kill e-w1 >/dev/null 2>&1
  dc exec -T -u postgres e-s1 pg_ctl -D $PGDATA promote -w >/dev/null 2>&1
  echo "standby writable after $(( $(date +%s) - T0 )) s; logical slots on it: $(qa e-s1 -c "select coalesce(string_agg(slot_name || ' failover=' || failover || ' active=' || active, ', '), 'none') from pg_replication_slots where slot_type = 'logical'")"
  # the promoted standby inherited synchronized_standby_slots = 'e_s1_slot', a slot it does not have
  # (nothing here plays pg_auto_failover's part): logical decoding would wait for it forever
  q e-s1 -c "alter system reset synchronized_standby_slots" -c "select pg_reload_conf()" >/dev/null
  dc exec -T e-s1 sh -c "for i in \$(seq 1000000 1000199); do psql -X -q -U postgres -d app -c \"insert into events values (\$i, 'new')\" 2>/dev/null; sleep 0.02; done"
  for i in $(seq 1 90); do
    [ "$(qa e-w2 -c "select count(*) from events where note = 'new'")" = 200 ] && break; sleep 1
  done
  echo "200 rows written on the new provider; on the subscriber: $(qa e-w2 -c "select count(*) from events where note = 'new'") (waited ${i}s after the last insert)"
  echo "subscription: $(qa e-w2 -c "select status from pglogical.show_subscription_status()")"
  qa e-s1 -c "select id from events order by 1" > results/e-failover-new.ids; qa e-w2 -c "select id from events order by 1" > results/e-failover-sub.ids
  echo "rows on the new provider $(wc -l < results/e-failover-new.ids | tr -d ' '), on the subscriber $(wc -l < results/e-failover-sub.ids | tr -d ' '); missing on the subscriber $(comm -23 results/e-failover-new.ids results/e-failover-sub.ids | wc -l | tr -d ' ')"
  echo "subscriber log: $(dc logs --tail 600 e-w2 2>&1 | grep -m2 'does not exist\|could not connect' | sed 's/^[^|]*| //' | cut -c1-220)"
  rm -f results/e-failover-new.ids results/e-failover-sub.ids
  } 2>&1 | tee "$out"
}

# bench <native|pglogical|pgcopydb>: one-way link e-w1 -> e-w2 (Postgres 18, no standbys), same
# table, same three workloads: latency of single-row transactions, rows a second under 8
# concurrent single-row writers, and one transaction of a million rows.
bench() {
  local M=${1:?native | pglogical | pgcopydb} out=results/e-bench-$1.out
  local TBL="create table events (id bigserial primary key, payload text not null, src_ts timestamptz not null default clock_timestamp(), applied_at timestamptz)"
  # the target stamps the time a row is applied, whichever tool applied it
  local TRG="create function stamp() returns trigger language plpgsql as \$\$ begin new.applied_at := clock_timestamp(); return new; end \$\$;
create trigger stamp before insert on events for each row execute function stamp();
alter table events enable always trigger stamp"
  {
  echo "== $M: e-w1 -> e-w2, PostgreSQL 18 =="
  case "$M" in
    native)
      q e-w1 -c "$TBL" -c "create publication bench for table events" >/dev/null
      q e-w2 -c "$TBL" -c "$TRG" >/dev/null
      q e-w2 -c "create subscription bench connection 'host=e-w1 dbname=app user=postgres' publication bench with (copy_data = false)" >/dev/null ;;
    pglogical)
      q e-w1 -c "create extension if not exists pglogical" -c "$TBL" >/dev/null
      q e-w1 -c "select pglogical.create_node(node_name := 'src', dsn := 'host=e-w1 dbname=app user=postgres')" -c "select pglogical.replication_set_add_table('default', 'events')" >/dev/null
      q e-w2 -c "create extension if not exists pglogical" -c "$TBL" -c "$TRG" >/dev/null
      q e-w2 -c "select pglogical.create_node(node_name := 'dst', dsn := 'host=e-w2 dbname=app user=postgres')" >/dev/null
      q e-w2 -c "select pglogical.create_subscription(subscription_name := 'bench', provider_dsn := 'host=e-w1 dbname=app user=postgres', synchronize_data := false)" >/dev/null
      wait_for e-w2 "(select count(*) from pglogical.show_subscription_status() where status = 'replicating') = 1" 60 ;;
    pgcopydb)
      q e-w1 -c "$TBL" >/dev/null
      COMPOSE_PROFILES=e dc up -d pgcopydb-e >/dev/null 2>&1
      dc exec -T pgcopydb-e sh -c "rm -rf /root/.local/share/pgcopydb /tmp/pgcopydb"
      dc exec -d pgcopydb-e sh -c "pgcopydb clone --follow --source 'postgres://postgres@e-w1/app' --target 'postgres://postgres@e-w2/app' > /results/e-bench-pgcopydb.log 2>&1"
      for i in $(seq 1 60); do [ "$(qa e-w2 -c "select to_regclass('public.events') is not null")" = t ] && break; sleep 1; done
      q e-w2 -c "$TRG" >/dev/null
      sleep 5 ;;
  esac
  cnt() { qa "$1" -c "select count(*) from events where payload = '$2'"; }
  now() { date +%s.%N; }
  drain() { # <payload> <expected>: seconds until the target has them all
    local t0=$(now) i
    for i in $(seq 1 ${DRAIN_TRIES:-1500}); do [ "$(cnt e-w2 "$1" 2>/dev/null)" -ge "$2" ] 2>/dev/null && break; sleep 0.2; done
    echo "$(now) $t0" | awk '{printf "%.1f", $1 - $2}'
  }

  # the link must carry a row before anything is measured
  q e-w1 -c "insert into events (payload) values ('canary')" >/dev/null
  if [ "$(drain canary 1 | cut -d. -f1)" -ge 60 ]; then echo "the link did not come up: no row on e-w2 after 60 s"; return 1; fi
  echo; echo "-- latency: 1000 single-row transactions, one session, 50 ms apart"
  dc exec -T e-w1 sh -c "for i in \$(seq 1 1000); do psql -X -q -U postgres -d app -c \"insert into events (payload) values ('lat')\"; sleep 0.05; done"
  drain lat 1000 >/dev/null
  qa e-w2 -c "select 'p50 ' || round((percentile_cont(0.5) within group (order by extract(epoch from applied_at - src_ts)) * 1000)::numeric, 1) || ' ms, p95 ' || round((percentile_cont(0.95) within group (order by extract(epoch from applied_at - src_ts)) * 1000)::numeric, 1) || ' ms, p99 ' || round((percentile_cont(0.99) within group (order by extract(epoch from applied_at - src_ts)) * 1000)::numeric, 1) || ' ms, rows ' || count(*) from events where payload = 'lat'"

  echo; echo "-- throughput: pgbench, 8 clients, 30 s, one insert per transaction"
  dc exec -T e-w1 sh -c "echo \"insert into events (payload) values ('tp');\" > /tmp/ins.sql"
  local t0=$(now)
  dc exec -T e-w1 pgbench -n -c 8 -j 4 -T 30 -U postgres -f /tmp/ins.sql app > /tmp/bench.$$ 2>&1
  local at_end=$(cnt e-w2 tp) src=$(cnt e-w1 tp)
  local d=$(drain tp $src)
  grep "tps =" /tmp/bench.$$ | sed 's/^/   source: /'; rm -f /tmp/bench.$$
  echo "   source committed $src rows; $at_end were on the target when the load stopped; the rest took $d s more"
  echo "   target applied $(awk -v n=$src -v d=$d 'BEGIN { printf "%d", n / (30 + d) }') rows/s over the whole run, $(awk -v n=$at_end 'BEGIN { printf "%d", n / 30 }') rows/s while it was loaded"

  echo; echo "-- one transaction of 1,000,000 rows"
  local tb=$(now)
  q e-w1 -c "insert into events (payload) select 'bulk' from generate_series(1, 1000000)" >/dev/null
  local sec=$(echo "$(now) $tb" | awk '{printf "%.1f", $1 - $2}')
  local dd=$(drain bulk 1000000)
  echo "   committed on the source after $sec s, complete on the target $dd s after that"
  } 2>&1 | tee "$out"
}

case "${1:-}" in
  findings)   findings ;;
  concurrent) concurrent ;;
  ddl)        ddl ;;
  failover)   failover ;;
  bench)      bench "${2:-}" ;;
  policy)     ensure_nodes; run_policy "$2" "${3:-15}" ;;
  *) echo "usage: $0 findings | concurrent | ddl | failover | bench <method> | policy <name> [secs]" >&2; exit 2 ;;
esac
